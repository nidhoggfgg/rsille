#[derive(Clone, Copy, Debug)]
pub struct Pose {
    pub x: f32,
    pub y: f32,
    pub lean: f32,
    pub squash: f32,
    pub arms: [f32; 2],
    pub attack: f32,
    pub hit: f32,
    pub joy: f32,
    pub lag: f32,
    pub head: f32,
    pub gaze: f32,
}

fn sample(keys: &[Key], time: f64) -> [f32; 9] {
    let t = time.rem_euclid(PERIOD) as f32;
    let i = keys
        .partition_point(|k| k[0] <= t)
        .saturating_sub(1)
        .min(keys.len() - 2);
    let (a, b) = (keys[i], keys[i + 1]);
    let prev = if i == 0 {
        let mut k = keys[keys.len() - 2];
        k[0] -= 24.;
        k
    } else {
        keys[i - 1]
    };
    let next = if i + 2 == keys.len() {
        let mut k = keys[1];
        k[0] += 24.;
        k
    } else {
        keys[i + 2]
    };
    let dt = b[0] - a[0];
    let u = ((t - a[0]) / dt).clamp(0., 1.);
    std::array::from_fn(|c| {
        let c = c + 1;
        let ma = (b[c] - prev[c]) / (b[0] - prev[0]);
        let mb = (next[c] - a[c]) / (next[0] - a[0]);
        (2. * u * u * u - 3. * u * u + 1.) * a[c]
            + (u * u * u - 2. * u * u + u) * dt * ma
            + (-2. * u * u * u + 3. * u * u) * b[c]
            + (u * u * u - u * u) * dt * mb
    })
}

pub fn poses(time: f64) -> [Pose; 3] {
    let t = time.rem_euclid(PERIOD) as f32;
    std::array::from_fn(|i| {
        let keys = [DEEPSEEK, CLAUDE, GPT][i];
        let p = sample(keys, time);
        let delayed = sample(keys, time - 0.18);
        let idle = (t * TAU / 3. + i as f32 * 1.7).sin();
        Pose {
            x: p[0],
            y: p[1] + idle * 0.35,
            lean: p[2],
            squash: p[3] + idle * 0.015,
            arms: [p[4], p[5]],
            attack: p[6].clamp(0., 1.),
            hit: p[7].clamp(0., 1.),
            joy: p[8].clamp(0., 1.),
            lag: ((delayed[0] - p[0]) * 0.28).clamp(-6., 6.),
            head: (delayed[2] - p[2]) * 0.65 + idle * 0.025,
            gaze: if i == 2 { -0.7 } else { 0.7 },
        }
    })
}

pub struct Beat {
    pub poses: [Pose; 3],
}
impl Beat {
    pub fn at(time: f64) -> Self {
        Self { poses: poses(time) }
    }
}
